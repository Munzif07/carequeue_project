// ══════════════════════════════════════════════════════════════
//  Language Switcher Widget — place in any screen AppBar/header
// ══════════════════════════════════════════════════════════════
class LangSwitcher extends StatelessWidget {
  final Color? activeColor;
  final Color? inactiveColor;
  const LangSwitcher({Key? key, this.activeColor, this.inactiveColor}) : super(key: key);

  @override
  Widget build(BuildContext context) {
    return ValueListenableBuilder<AppLang>(
      valueListenable: langNotifier,
      builder: (_, cur, __) {
        return Container(
          margin: const EdgeInsets.only(right: 8),
          padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 4),
          decoration: BoxDecoration(
            color: Colors.white.withOpacity(0.15),
            borderRadius: BorderRadius.circular(20),
          ),
          child: Row(
            mainAxisSize: MainAxisSize.min,
            children: AppLang.values.map((lang) {
              final active = cur == lang;
              final label  = lang == AppLang.en ? 'EN'
                           : lang == AppLang.ta ? 'த'
                           : 'සි';
              return GestureDetector(
                onTap: () => Lang.set(lang),
                child: AnimatedContainer(
                  duration: const Duration(milliseconds: 200),
                  padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                  decoration: BoxDecoration(
                    color: active ? Colors.white : Colors.transparent,
                    borderRadius: BorderRadius.circular(14),
                  ),
                  child: Text(label,
                    style: TextStyle(
                      fontSize: 12,
                      fontWeight: FontWeight.w700,
                      color: active
                        ? (activeColor ?? const Color(0xFF1a6b5a))
                        : (inactiveColor ?? Colors.white),
                    ),
                  ),
                ),
              );
            }).toList(),
          ),
        );
      },
    );
  }
}
