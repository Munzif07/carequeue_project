// ── Language codes ───────────────────────────────────────────
enum AppLang { en, ta, si }

// ── Global notifier (whole app rebuilds when lang changes) ───
final langNotifier = ValueNotifier<AppLang>(AppLang.en);

class Lang {
  static AppLang get current => langNotifier.value;

  // ── Load saved language from device ──────────────────────
  static Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    final code  = prefs.getString('app_lang') ?? 'en';
    langNotifier.value = code == 'ta' ? AppLang.ta
                       : code == 'si' ? AppLang.si
                       : AppLang.en;
  }

  // ── Save + switch language ────────────────────────────────
  static Future<void> set(AppLang lang) async {
    langNotifier.value = lang;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('app_lang', lang.name);
  }

  // ── Translate ─────────────────────────────────────────────
  static String t(String key) {
    final map = _strings[current];
    return map?[key] ?? _strings[AppLang.en]?[key] ?? key;
  }

